/** Official Colliers Project Leaders offices (Excel office locations). */
export function officeDisplayName(raw) {
  var name = String(raw || '')
    .replace(/\s*\([^)]*\)\s*/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
  if (!name) return ''
  if (/office$/i.test(name)) return name
  return name + ' Office'
}

